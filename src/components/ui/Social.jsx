export function SocialIcon({ name, className }) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="1.75"
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      className={cn('size-[18px]', className)}
    >
      {PATHS[name] || PATHS.link}
    </svg>
  );
}

export function SocialLinks({ socials, round = true, label = '', className }) {
  const entries = Object.entries(socials || {}).filter(([, url]) => url);
  if (!entries.length) return null;
  return (
    <div className={cn('flex flex-wrap gap-2', className)}>
      {entries.map(([name, url]) => (
        <a
          key={name}
          href={url}
          target="_blank"
          rel="noopener noreferrer"
          aria-label={label ? `${label} on ${name}` : name}
          className={cn(
            'inline-grid size-11 place-items-center border border-border text-muted transition-[color,border-color,box-shadow] duration-250',
            'hover:border-green-bright/60 hover:text-green-bright hover:shadow-[0_0_18px_-4px_rgba(70,196,107,.45)]',
            round ? 'rounded-full bg-surface' : 'rounded-[10px]',
          )}
        >
          <SocialIcon name={name} />
        </a>
      ))}
    </div>
  );
}
